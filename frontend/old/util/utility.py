def get_style_path(name: str) -> str:
    return f"/static/styles/{name}"

def get_script_path(name: str) -> str:
    return f"/static/scripts/{name}"

def get_logo_path(name: str) -> str:
    return f"/static/assets/logo/{name}"

def get_icon_path(name: str) -> str:
    return f"/static/assets/icon/{name}"